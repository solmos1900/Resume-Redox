import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outCss = path.join(root, "tmp-export-resume.css");
const outTs = path.join(root, "lib/export/generated/export-resume-css.ts");
const tailwindBin = path.join(root, "node_modules/.bin/tailwindcss");

fs.mkdirSync(path.dirname(outTs), { recursive: true });

execFileSync(
  tailwindBin,
  [
    "-c",
    "tailwind.export.config.ts",
    "-i",
    "./styles/export-entry.css",
    "-o",
    outCss,
    "--minify",
  ],
  { cwd: root, stdio: "inherit" }
);

const css = fs.readFileSync(outCss, "utf8");
fs.writeFileSync(
  outTs,
  `/** Auto-generated by scripts/build-export-css.mjs — do not edit. */\n` +
    `export const EXPORT_RESUME_CSS = ${JSON.stringify(css)};\n`
);
fs.unlinkSync(outCss);
console.log(`Wrote ${path.relative(root, outTs)} (${css.length} bytes CSS)`);
